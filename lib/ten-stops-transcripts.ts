// ─── The follow-along model (hand-written — the data above is generated) ────
// The player's TRANSCRIPT section reads the tour through these
// two lenses: rows (the segments grouped under their stop) and
// the active segment (the one being spoken at a position).

/** One render row of the transcript: a group header (a stop's
 * title and passage, or the Introduction) or one segment. A
 * segment's `index` is its place in the tour's segment list —
 * the identity the active light and the layout map key on. */
export type TenStopsTranscriptRow =
  | { kind: 'header'; label: string; passage?: string }
  | { kind: 'segment'; index: number; startSec: number; text: string };

/**
 * The transcript as render rows: segments in spoken order, each
 * grouped under the latest stop whose startSec is at or before
 * the segment's own start — a segment belongs to the stop the
 * tour was inside when it was spoken. Segments before Stop 1
 * sit under an "Introduction" header. Headers appear only where
 * a group actually holds segments.
 */
export function tenStopsTranscriptRows(
  segments: readonly DevotionalTranscriptSegment[],
  movements: readonly DevotionalMovement[],
): TenStopsTranscriptRow[] {
  const rows: TenStopsTranscriptRow[] = [];
  let currentKey: string | null = null;
  segments.forEach((seg, index) => {
    let stopIdx = -1;
    movements.forEach((m, i) => {
      if (m.startSec <= seg.startSec) stopIdx = i;
    });
    const key = stopIdx < 0 ? 'introduction' : `stop-${stopIdx}`;
    if (key !== currentKey) {
      currentKey = key;
      rows.push(
        stopIdx < 0
          ? { kind: 'header', label: 'Introduction' }
          : { kind: 'header', label: movements[stopIdx].title, passage: movements[stopIdx].passage },
      );
    }
    rows.push({ kind: 'segment', index, startSec: seg.startSec, text: seg.text });
  });
  return rows;
}

/**
 * The segment being spoken at `positionSec`: the last segment
 * whose startSec is at or before the position. -1 when the
 * position precedes the first segment (no segment is lit before
 * the tour begins speaking).
 */
export function activeTenStopsTranscriptSegment(
  segments: readonly DevotionalTranscriptSegment[],
  positionSec: number,
): number {
  let active = -1;
  for (let i = 0; i < segments.length; i++) {
    if (segments[i].startSec <= positionSec) active = i;
    else break;
  }
  return active;
}
