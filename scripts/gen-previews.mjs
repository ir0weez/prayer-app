#!/usr/bin/env node
// ─── v207 storyteller previews — bake the per-book JSON into the app ────────
// The Personal Study card's "Last time in… / This time in… / cliffhanger"
// previews ship as LOCAL DATA (his call, 2026-10-23), generated ahead of
// time book by book — never fetched live. This script embeds whatever
// books currently exist as JSON into lib/bible-v205/previews.ts:
//
//   PREVIEWS_DIR/<Book>.json   { "<chapter>": { "recap": "…",
//                                               "preview": "…",
//                                               "question": "…" } }
//
// Default source dir: ~/workspace/goals/prayercircle-apk-build/
// hidden_files/previews (the generation pass's output). A missing or
// empty dir is NOT an error: PREVIEWS ships empty and every chapter
// simply has no baked preview yet (the card shows position lines).
// Overrides (used by the fixture test): PREVIEWS_DIR, PREVIEWS_OUT.

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir =
  process.env.PREVIEWS_DIR ??
  resolve(root, '../goals/prayercircle-apk-build/hidden_files/previews');
const out = process.env.PREVIEWS_OUT ?? join(root, 'lib/bible-v205/previews.ts');

const data = {};
const embedded = [];
if (existsSync(dir)) {
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
    const book = file.slice(0, -'.json'.length);
    let parsed;
    try {
      parsed = JSON.parse(readFileSync(join(dir, file), 'utf8'));
    } catch (e) {
      console.error(`gen-previews: skipping ${file} — invalid JSON (${e.message})`);
      continue;
    }
    const chapters = {};
    for (const [key, value] of Object.entries(parsed ?? {})) {
      const chapter = parseInt(key, 10);
      // Genesis 1 is the one chapter with no "last time": its recap is
      // empty BY DESIGN in the source data and is never rendered
      // (preview.ts composes no last-time label for it). Every other
      // chapter must carry all three beats, non-empty.
      const recapOk =
        typeof value?.recap === 'string' &&
        (value.recap.trim() !== '' || (book === 'Genesis' && chapter === 1));
      const ok =
        Number.isFinite(chapter) &&
        value &&
        recapOk &&
        typeof value.preview === 'string' && value.preview.trim() &&
        typeof value.question === 'string' && value.question.trim();
      if (!ok) {
        console.error(`gen-previews: skipping ${book} ${key} — needs non-empty recap/preview/question strings`);
        continue;
      }
      chapters[chapter] = {
        recap: value.recap,
        preview: value.preview,
        question: value.question,
      };
    }
    if (Object.keys(chapters).length) {
      data[book] = chapters;
      embedded.push(book);
    }
  }
} else {
  console.error(`gen-previews: source dir not found (${dir}) — embedding zero books`);
}

const body = `// AUTO-GENERATED by scripts/gen-previews.mjs — do not edit by hand.
// Baked storyteller previews for the Personal Study card, composed by
// lib/bible-v205/preview.ts. Books embedded: ${embedded.length ? embedded.join(', ') : 'none yet'}.

export interface ChapterPreview {
  recap: string;
  preview: string;
  question: string;
}

export const PREVIEWS: Record<string, Record<number, ChapterPreview>> = ${JSON.stringify(data, null, 2)};
`;

writeFileSync(out, body);
console.log(
  `gen-previews: embedded ${embedded.length} book(s) -> ${out}` +
    (embedded.length ? `: ${embedded.join(', ')}` : ''),
);
